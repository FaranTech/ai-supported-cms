// One-off script: embeds each policy document with Gemini's free embedding
// model and writes the vectors to src/data/policy-embeddings.js, so the real
// RAG tool (api/lib/rag.js) can do cosine-similarity search at request time
// without re-embedding the whole corpus on every query.
//
// Usage: node --env-file=.env scripts/embed-policies.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { GoogleGenerativeAI } from "@google/generative-ai";
import { policies } from "../src/data/policies.js";

const apiKey = process.env.GEMINI_API_KEY;
if (!apiKey) {
  console.error(
    "Missing GEMINI_API_KEY. Put it in .env and run:\n" +
      "  node --env-file=.env scripts/embed-policies.mjs"
  );
  process.exit(1);
}

const genAI = new GoogleGenerativeAI(apiKey);
const model = genAI.getGenerativeModel({ model: "gemini-embedding-001" });

const embeddings = [];
for (const policy of policies) {
  const { embedding } = await model.embedContent(
    `${policy.title}\n\n${policy.text}`
  );
  embeddings.push({ id: policy.id, vector: embedding.values });
  console.log(`embedded ${policy.id} — ${policy.title}`);
}

const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/data/policy-embeddings.js"
);
const contents =
  "// Generated by scripts/embed-policies.mjs — do not edit by hand.\n" +
  "// Re-run the script (with GEMINI_API_KEY set) whenever policies.js changes.\n" +
  `export const policyEmbeddings = ${JSON.stringify(embeddings, null, 2)};\n`;

writeFileSync(outPath, contents);
console.log(`\nWrote ${embeddings.length} embeddings to ${outPath}`);
